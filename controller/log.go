const logExportLimit = 5000

func writeLogsCSV(c *gin.Context, logs []*model.Log, filename string, includeAdminColumns bool) {
	buffer := &bytes.Buffer{}
	writer := csv.NewWriter(buffer)

	headers := []string{
		"time",
		"type",
		"model_name",
		"token_name",
		"group",
		"quota",
		"prompt_tokens",
		"completion_tokens",
		"use_time",
		"request_id",
		"ip",
		"content",
	}
	if includeAdminColumns {
		headers = append([]string{"username", "channel_id", "channel_name"}, headers...)
	}
	if err := writer.Write(headers); err != nil {
		common.ApiError(c, err)
		return
	}

	for _, log := range logs {
		record := []string{
			strconv.FormatInt(log.CreatedAt, 10),
			strconv.Itoa(log.Type),
			log.ModelName,
			log.TokenName,
			log.Group,
			strconv.Itoa(log.Quota),
			strconv.Itoa(log.PromptTokens),
			strconv.Itoa(log.CompletionTokens),
			strconv.Itoa(log.UseTime),
			log.RequestId,
			log.Ip,
			log.Content,
		}
		if includeAdminColumns {
			record = append([]string{
				log.Username,
				strconv.Itoa(log.ChannelId),
				log.ChannelName,
			}, record...)
		}
		if err := writer.Write(record); err != nil {
			common.ApiError(c, err)
			return
		}
	}
	writer.Flush()
	if err := writer.Error(); err != nil {
		common.ApiError(c, err)
		return
	}

	c.Header("Content-Disposition", "attachment; filename=\""+filename+"\"")
	c.Data(http.StatusOK, "text/csv; charset=utf-8", buffer.Bytes())
}

